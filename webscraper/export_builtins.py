#!/usr/bin/env python3
"""Converts scraped data_en.json / data.json into TypeScript files for VS Code extension.

Usage:
    python export_builtins.py --input data_en.json --output ../src/providers/gbBuiltins_en.ts --export-name gbBuiltinsEn
    python export_builtins.py --input data.json --output ../src/providers/gbBuiltins.ts --export-name gbBuiltins
"""

import argparse
import json
from pathlib import Path


def export_to_typescript(input_json_path: str, output_ts_path: str, export_name: str) -> None:
    input_file = Path(input_json_path)
    output_file = Path(output_ts_path)

    with open(input_file, "r", encoding="utf-8") as f:
        data = json.load(f)

    output_file.parent.mkdir(parents=True, exist_ok=True)

    with open(output_file, "w", encoding="utf-8") as f:
        f.write("/* Auto-generated by webscraper/export_builtins.py - DO NOT EDIT */\n\n")
        f.write(f"export const {export_name} = ")
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write(";\n")

    print(f"Exported {len(data)} notices from {input_json_path} to {output_ts_path} ({export_name})")


def main() -> None:
    parser = argparse.ArgumentParser(description="Export scraped Cast3M JSON to TypeScript.")
    parser.add_argument(
        "--input",
        "-i",
        default="data_en.json",
        help="Input JSON file path (default: data_en.json)",
    )
    parser.add_argument(
        "--output",
        "-o",
        default="../src/providers/gbBuiltins_en.ts",
        help="Output TypeScript file path (default: ../src/providers/gbBuiltins_en.ts)",
    )
    parser.add_argument(
        "--export-name",
        "-e",
        default="gbBuiltinsEn",
        help="Exported TypeScript variable name (default: gbBuiltinsEn)",
    )
    args = parser.parse_args()
    export_to_typescript(args.input, args.output, args.export_name)


if __name__ == "__main__":
    main()
